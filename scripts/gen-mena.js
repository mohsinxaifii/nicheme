// Builds src/data/mena.js: simplified SVG paths of every country in the MENA
// frame (Natural Earth 110m), flagged when it is one of Niche's 17 countries.
import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/countries-110m.json', import.meta.url)))
const NETWORK = new Set(['784', '682', '634', '414', '512', '048', '400', '422', '760', '368', '818', '504', '788', '012', '887', '586', '480'])
const B = { lon: [-18, 78], lat: [-22, 44] }
const S = 10 // px per degree
const W = (B.lon[1] - B.lon[0]) * S, H = (B.lat[1] - B.lat[0]) * S
const X = lon => ((lon - B.lon[0]) * S).toFixed(1), Y = lat => ((B.lat[1] - lat) * S).toFixed(1)

const out = []
for (const f of feature(topo, topo.objects.countries).features) {
  const g = f.geometry
  if (!g) continue
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates
  let d = '', inFrame = false
  for (const poly of polys) for (const ring of poly) {
    if (ring.some(([lon, lat]) => lon > B.lon[0] - 5 && lon < B.lon[1] + 5 && lat > B.lat[0] - 5 && lat < B.lat[1] + 5)) inFrame = true
    d += 'M' + ring.map(([lon, lat]) => `${X(lon)} ${Y(lat)}`).join('L') + 'Z'
  }
  if (!inFrame) continue
  const id = String(f.id).padStart(3, '0')
  out.push({ id, name: f.properties.name, net: NETWORK.has(id), d })
}
const cities = { dubai: [55.27, 25.2], riyadh: [46.68, 24.71], cairo: [31.24, 30.04], casablanca: [-7.59, 33.57], karachi: [67.0, 24.86], amman: [35.93, 31.95], doha: [51.53, 25.29], kuwait: [47.98, 29.38], muscat: [58.38, 23.59], manama: [50.59, 26.23], tunis: [10.18, 36.81], algiers: [3.06, 36.75], beirut: [35.5, 33.89], baghdad: [44.37, 33.32], sanaa: [44.19, 15.37], damascus: [36.28, 33.51], portlouis: [57.5, -20.16] }
const pts = Object.fromEntries(Object.entries(cities).map(([k, [lon, lat]]) => [k, [+X(lon), +Y(lat)]]))
writeFileSync(new URL('../src/data/mena.js', import.meta.url),
  `// Generated by scripts/gen-mena.js from Natural Earth 110m. Do not edit.\nexport const VIEW = [${W}, ${H}]\nexport const CITIES = ${JSON.stringify(pts)}\nexport const COUNTRIES = ${JSON.stringify(out)}\n`)
console.log(out.length, 'countries,', out.filter(c => c.net).length, 'in network')
